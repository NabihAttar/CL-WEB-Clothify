export function getWebsiteSchema() {
	return {
		"@context": "https://schema.org",
		"@type": "WebSite",
		name: siteConfig.name,
		url: siteConfig.url,
		description: siteConfig.description,
		publisher: {
			"@type": "Organization",
			name: siteConfig.name,
		},
	};
}

export function getFaqSchema(items = faqItems) {
	return {
		"@context": "https://schema.org",
		"@type": "FAQPage",
		mainEntity: items.map(({ question, answer }) => ({
			"@type": "Question",
			name: question,
			acceptedAnswer: {
				"@type": "Answer",
				text: answer,
			},
		})),
	};
}

export function getArticleSchema(item, id) {
	return {
		"@context": "https://schema.org",
		"@type": "BlogPosting",
		headline: item?.title,
		description: truncateDescription(item?.desc1 || item?.desc),
		image: item?.detailsImg || item?.img1 || item?.img
			? absoluteUrl(item.detailsImg || item.img1 || item.img)
			: absoluteUrl(siteConfig.ogImage),
		url: absoluteUrl(`/blogs/${id}`),
		datePublished: parseBlogDate(item?.date),
		author: {
			"@type": "Organization",
			name: siteConfig.name,
		},
		publisher: {
			"@type": "Organization",
			name: siteConfig.name,
			logo: {
				"@type": "ImageObject",
				url: absoluteUrl(siteConfig.ogImage),
			},
		},
	};
}
