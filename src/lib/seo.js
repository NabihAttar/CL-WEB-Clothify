export function absoluteUrl(path = "") {
	const base = siteConfig.url.replace(/\/$/, "");
	if (!path) {
		return `${base}/`;
	}

	return `${base}${path.startsWith("/") ? path : `/${path}`}`;
}

export function truncateDescription(text, maxLength = 160) {
	if (!text) {
		return siteConfig.description;
	}

	const cleaned = text.replace(/\s+/g, " ").trim();
	if (cleaned.length <= maxLength) {
		return cleaned;
	}

	const truncated = cleaned.slice(0, maxLength - 1);
	const lastSpace = truncated.lastIndexOf(" ");

	return `${(lastSpace > 80 ? truncated.slice(0, lastSpace) : truncated).trim()}…`;
}

export function createMetadata({
	title,
	description,
	path = "",
	image,
	imageAlt,
	imageWidth,
	imageHeight,
	noIndex = false,
	openGraphType = "website",
	publishedTime,
	modifiedTime,
	authors,
} = {}) {
	const pageTitle = title || siteConfig.title;
	const pageDescription = truncateDescription(description || siteConfig.description);
	const canonicalPath = path || "/";
	const ogImagePath = image || siteConfig.ogImage;
	const ogImageAlt = imageAlt || siteConfig.ogImageAlt;

	const openGraph = {
		type: openGraphType,
		locale: siteConfig.locale,
		url: canonicalPath,
		siteName: siteConfig.name,
		title: pageTitle,
		description: pageDescription,
		images: [
			{
				url: ogImagePath,
				width: imageWidth || siteConfig.ogImageWidth,
				height: imageHeight || siteConfig.ogImageHeight,
				alt: ogImageAlt,
			},
		],
	};

	if (openGraphType === "article") {
		if (publishedTime) {
			openGraph.publishedTime = publishedTime;
		}
		if (modifiedTime) {
			openGraph.modifiedTime = modifiedTime;
		}
		if (authors?.length) {
			openGraph.authors = authors;
		}
	}

	return {
		title: {
			absolute: pageTitle,
		},
		description: pageDescription,
		alternates: {
			canonical: canonicalPath,
		},
		robots: noIndex
			? { index: false, follow: false }
			: {
					index: true,
					follow: true,
					googleBot: {
						index: true,
						follow: true,
						"max-image-preview": "large",
						"max-snippet": -1,
						"max-video-preview": -1,
					},
				},
		openGraph,
		twitter: {
			card: "summary_large_image",
			title: pageTitle,
			description: pageDescription,
			images: [
				{
					url: ogImagePath,
					alt: ogImageAlt,
				},
			],
		},
	};
}

export function createPageMetadata(pageKey, overrides = {}) {
	const page = pageSeo[pageKey];

	if (!page) {
		return createMetadata(overrides);
	}

	const { noIndex, image, imageAlt, ...pageMeta } = page;

	return createMetadata({
		title: pageMeta.title,
		description: pageMeta.description,
		path: pageMeta.path,
		image,
		imageAlt,
		noIndex: noIndex ?? false,
		...overrides,
	});
}

