function parseBlogDate(dateString) {
	if (!dateString) {
		return undefined;
	}

	const trimmed = String(dateString).trim();

	// Handles display formats such as "Jul 28, 2025" and "January 3, 2025".
	const parsed = new Date(trimmed);
	if (!Number.isNaN(parsed.getTime())) {
		return parsed.toISOString();
	}

	// Fallback for abbreviated month + zero-padded day formats like "Nov 06, 2025".
	const normalized = trimmed.replace(
		/^([A-Za-z]{3})\s+0(\d{1,2}),\s*(\d{4})$/,
		"$1 $2, $3"
	);
	const retry = new Date(normalized);

	return Number.isNaN(retry.getTime()) ? undefined : retry.toISOString();
}

export function getBlogLastModified(dateString) {
	const isoDate = parseBlogDate(dateString);

	return isoDate ? new Date(isoDate) : undefined;
}

